import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { asc } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/node-postgres';
import type { NodePgDatabase } from 'drizzle-orm/node-postgres';
import { pgMigrations } from '@/infrastructure/persistence/Migrations';

vi.mock('@/shared/utils/logger', () => ({
  logger: {
    debug: vi.fn(),
    info: vi.fn(),
    warn: vi.fn(),
    error: vi.fn(),
    banner: vi.fn(),
  },
}));

import { migrationService } from '@/infrastructure/database/migration.service';
import {
  createPreMigrationSchema,
  dropMigrationSurface,
  hasPostgresEnv,
  initMigrationsTable,
  objectNames,
  pgConnectionString,
  tableColumns,
} from './helpers';

// Runs against a real Postgres when POSTGRES_* env values are provided
// (docker-compose.yaml); skipped otherwise, like the other DB-backed suites.
describe.skipIf(!hasPostgresEnv)('MigrationService (integration, real postgres)', () => {
  let db: NodePgDatabase<Record<string, never>> & { $client: { end: () => Promise<void> } };

  beforeAll(() => {
    db = drizzle(pgConnectionString);
  });

  afterAll(async () => {
    await db.$client.end();
  });

  beforeEach(async () => {
    await dropMigrationSurface(db);
    await createPreMigrationSchema(db);
    await initMigrationsTable(db);
  });

  it('run() applies both pending migrations of the real MIGRATIONS registry', async () => {
    await migrationService.run(db);

    const applied = await db.select().from(pgMigrations).orderBy(asc(pgMigrations.version));
    expect(applied.map((m) => m.version)).toEqual(['001', '002']);
    // appliedAt is generated by the code itself: assert shape, not value
    expect(applied.every((m) => m.appliedAt instanceof Date)).toBe(true);

    // 001 renamed the historic_data columns to camelCase
    const columns = await tableColumns(db, 'historic_data');
    expect(columns).toContain('stationId');
    expect(columns).toContain('stationSignage');
    expect(columns).toContain('gasoilAPrice');
    expect(columns).not.toContain('station_id');

    // 002 created the historic_no_data table and the unique index
    const objects = await objectNames(db);
    expect(objects).toContain('historic_no_data');
    expect(objects).toContain('idx_historic_station_date');
  });

  it('run() is idempotent: a second run leaves the database unchanged', async () => {
    await migrationService.run(db);
    await migrationService.run(db);

    expect(await countMigrations(db)).toBe(2);
    const columns = await tableColumns(db, 'historic_data');
    expect(columns).toContain('stationId');
    expect(columns).not.toContain('station_id');
  });

  it('status() reflects pending migrations before run() and applied after', async () => {
    let status = await migrationService.status(db);
    expect(status).toEqual([
      { version: '001', name: 'baseline', applied: false },
      { version: '002', name: 'unique_station_date', applied: false },
    ]);

    await migrationService.run(db);

    status = await migrationService.status(db);
    expect(status).toEqual([
      { version: '001', name: 'baseline', applied: true },
      { version: '002', name: 'unique_station_date', applied: true },
    ]);
  });

  it('rollback(1) reverts the last applied migration twice down to an empty registry', async () => {
    await migrationService.run(db);

    await migrationService.rollback(db, 1);

    expect(await countMigrations(db)).toBe(1);
    const objects = await objectNames(db);
    expect(objects).not.toContain('historic_no_data');
    expect(objects).not.toContain('idx_historic_station_date');
    expect(await tableColumns(db, 'historic_data')).toContain('stationId');

    await migrationService.rollback(db, 1);

    expect(await countMigrations(db)).toBe(0);
    const columns = await tableColumns(db, 'historic_data');
    expect(columns).toContain('station_id');
    expect(columns).not.toContain('stationId');
  });

  it('getLastAppliedVersion() tracks the applied versions', async () => {
    expect(await migrationService.getLastAppliedVersion(db)).toBeNull();

    await migrationService.run(db);
    expect(await migrationService.getLastAppliedVersion(db)).toBe('002');

    await migrationService.rollback(db, 1);
    expect(await migrationService.getLastAppliedVersion(db)).toBe('001');
  });

  it('isDbEmpty() is false once the public schema has tables', async () => {
    expect(await migrationService.isDbEmpty(db)).toBe(false);
  });
});

const countMigrations = async (db: NodePgDatabase<Record<string, never>>): Promise<number> =>
  (await db.select().from(pgMigrations)).length;
