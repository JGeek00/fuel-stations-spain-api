import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

vi.mock('@/utils/logger', () => ({
  logger: {
    debug: vi.fn(),
    info: vi.fn(),
    warn: vi.fn(),
    error: vi.fn(),
    banner: vi.fn(),
  },
}));

import { migrationService } from '@/services/migration.service';
import { Migrations, MigrationsAttributes } from '@/models/db/Migrations';
import {
  createPreMigrationSchema,
  createSqlite,
  initMigrationsModel,
  sqliteObjectNames,
  tableColumns,
} from './helpers';

let sequelize: ReturnType<typeof createSqlite>;

describe('MigrationService (integration, real in-memory sqlite)', () => {
  beforeEach(async () => {
    sequelize = createSqlite();
    await initMigrationsModel(sequelize);
    await createPreMigrationSchema(sequelize);
  });

  afterEach(async () => {
    await sequelize.close();
  });

  it('run() applies both pending migrations of the real MIGRATIONS registry', async () => {
    await migrationService.run(sequelize);

    const applied = (await Migrations.findAll({ order: [['version', 'ASC']] })).map(
      (m) => m.get({ plain: true }) as unknown as MigrationsAttributes
    );
    expect(applied.map((m) => m.version)).toEqual(['001', '002']);
    // appliedAt is generated by the code itself: assert shape, not value
    expect(applied.every((m) => m.appliedAt instanceof Date)).toBe(true);

    // 001 renamed the historic_data columns to camelCase
    const columns = await tableColumns(sequelize, 'historic_data');
    expect(columns).toContain('stationId');
    expect(columns).toContain('stationSignage');
    expect(columns).toContain('gasoilAPrice');
    expect(columns).not.toContain('station_id');

    // 002 created the historic_no_data table and the unique index
    const objects = await sqliteObjectNames(sequelize);
    expect(objects).toContain('historic_no_data');
    expect(objects).toContain('idx_historic_station_date');
  });

  it('run() is idempotent: a second run leaves the database unchanged', async () => {
    await migrationService.run(sequelize);
    await migrationService.run(sequelize);

    expect(await Migrations.count()).toBe(2);
    const columns = await tableColumns(sequelize, 'historic_data');
    expect(columns).toContain('stationId');
    expect(columns).not.toContain('station_id');
  });

  it('status() reflects pending migrations before run() and applied after', async () => {
    let status = await migrationService.status(sequelize);
    expect(status).toEqual([
      { version: '001', name: 'baseline', applied: false },
      { version: '002', name: 'unique_station_date', applied: false },
    ]);

    await migrationService.run(sequelize);

    status = await migrationService.status(sequelize);
    expect(status).toEqual([
      { version: '001', name: 'baseline', applied: true },
      { version: '002', name: 'unique_station_date', applied: true },
    ]);
  });

  it('rollback(1) reverts the last applied migration twice down to an empty registry', async () => {
    await migrationService.run(sequelize);

    await migrationService.rollback(sequelize, 1);

    expect(await Migrations.count()).toBe(1);
    const objects = await sqliteObjectNames(sequelize);
    expect(objects).not.toContain('historic_no_data');
    expect(objects).not.toContain('idx_historic_station_date');
    expect(await tableColumns(sequelize, 'historic_data')).toContain('stationId');

    await migrationService.rollback(sequelize, 1);

    expect(await Migrations.count()).toBe(0);
    const columns = await tableColumns(sequelize, 'historic_data');
    expect(columns).toContain('station_id');
    expect(columns).not.toContain('stationId');
  });

  it('getLastAppliedVersion() tracks the applied versions', async () => {
    expect(await migrationService.getLastAppliedVersion(sequelize)).toBeNull();

    await migrationService.run(sequelize);
    expect(await migrationService.getLastAppliedVersion(sequelize)).toBe('002');

    await migrationService.rollback(sequelize, 1);
    expect(await migrationService.getLastAppliedVersion(sequelize)).toBe('001');
  });

  it('isDbEmpty() is postgres-specific: it rejects on sqlite (no information_schema)', async () => {
    await expect(migrationService.isDbEmpty(sequelize)).rejects.toThrow(/information_schema/);
  });
});
