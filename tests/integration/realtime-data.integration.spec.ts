import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { CreationAttributes } from 'sequelize';

vi.mock('@/utils/logger', () => ({
  logger: {
    debug: vi.fn(),
    info: vi.fn(),
    warn: vi.fn(),
    error: vi.fn(),
    banner: vi.fn(),
  },
}));

// The typia transform does not run under vitest (esbuild), so the runtime
// module cannot assert — same treatment as tests/unit/services/data-provider-api.service.spec.ts
vi.mock('typia', () => ({
  default: {
    assert: vi.fn((value: unknown) => value),
  },
}));

import { realtimeDataService } from '@/services/realtime-data.service';
import { FuelStationsTable } from '@/models/db/FuelStations';
import { LastUpdated, LastUpdatedAttributes } from '@/models/db/LastUpdated';
import type { FuelStation } from '@/models/entities';
import MunicipalitiesRepository from '@/repository/Municipalities.repository';
import { logger } from '@/utils/logger';
import {
  createSqlite,
  initMemoryModels,
  municipalitiesResponse,
  stationEntry,
  stationsResponse,
  stubProviderFetch,
} from './helpers';

let sequelize: ReturnType<typeof createSqlite>;

const seedStation = async (overrides: Partial<CreationAttributes<FuelStationsTable>> = {}) => {
  await FuelStationsTable.create({
    id: '00000000-0000-4000-8000-000000000001',
    stationId: 'ESOLD',
    locality: 'Old town',
    ...overrides,
  } as CreationAttributes<FuelStationsTable>);
};

describe('RealtimeDataService.loadAll (integration, real in-memory sqlite)', () => {
  beforeEach(async () => {
    sequelize = createSqlite();
    await initMemoryModels(sequelize);
    MunicipalitiesRepository.data = [];
  });

  afterEach(async () => {
    vi.unstubAllGlobals();
    MunicipalitiesRepository.data = [];
    await sequelize.close();
  });

  it('replaces station rows from the provider and stamps LastUpdated', async () => {
    await seedStation();
    stubProviderFetch({
      stations: stationsResponse([
        stationEntry(),
        stationEntry({ IDEESS: 'ES000456', Localidad: 'Getafe', 'Precio Gasolina 95 E5': '' }),
      ]),
      municipalities: municipalitiesResponse(),
    });

    await realtimeDataService.loadAll();

    const rows = (await FuelStationsTable.findAll({ order: [['stationId', 'ASC']] })).map(
      (r) => r.get({ plain: true }) as unknown as FuelStation & { id: string }
    );
    expect(rows).toHaveLength(2);

    const first = rows[0];
    expect(first.stationId).toBe('ES000123');
    expect(first.locality).toBe('Madrid');
    expect(first.address).toBe('Calle Test 1');
    expect(first.gasoilAPrice).toBe(1.5);
    expect(first.gasoline95E5Price).toBe(1.65);
    expect(first.municipalityId).toBe(28079);
    expect(first.provinceId).toBe(28);
    expect(first.regionId).toBe(29);
    // id is generated by the code itself: assert shape, not value
    expect(first.id).toMatch(/^[0-9a-f-]{36}$/);

    // a station with empty price strings maps to null prices
    const second = rows[1];
    expect(second.stationId).toBe('ES000456');
    expect(second.locality).toBe('Getafe');
    expect(second.gasoline95E5Price).toBeNull();

    // the previously seeded row was truncated
    expect(rows.some((r) => r.stationId === 'ESOLD')).toBe(false);

    const lastUpdated = (await LastUpdated.findAll()).map(
      (r) => r.get({ plain: true }) as unknown as LastUpdatedAttributes
    );
    expect(lastUpdated).toHaveLength(1);
    // lastUpdated is generated by the code itself: assert shape, not value
    expect(lastUpdated[0].lastUpdated).toBeInstanceOf(Date);

    // loadAll also feeds the in-memory municipalities repository
    expect(MunicipalitiesRepository.data).toHaveLength(1);
  });

  it('keeps previous data untouched when the provider fetch fails', async () => {
    await seedStation();
    await LastUpdated.create({ lastUpdated: new Date('2024-01-01T00:00:00') });
    const fetchMock = stubProviderFetch({ reject: new Error('Network down') });

    await realtimeDataService.loadAll();

    expect(fetchMock).toHaveBeenCalled();
    expect(await FuelStationsTable.count()).toBe(1);
    expect(
      ((await FuelStationsTable.findAll())[0].get({ plain: true }) as unknown as FuelStation).stationId
    ).toBe('ESOLD');
    expect(await LastUpdated.count()).toBe(1);
    expect(logger.error).toHaveBeenCalled();
  });

  it('tolerates a malformed stations payload without touching the database', async () => {
    await seedStation();
    stubProviderFetch({
      stations: {}, // no ListaEESSPrecio
      municipalities: municipalitiesResponse(),
    });

    await realtimeDataService.loadAll();

    expect(await FuelStationsTable.count()).toBe(1);
    expect(await LastUpdated.count()).toBe(0);
    expect(logger.error).toHaveBeenCalled();
    // the municipalities feed still landed in the repository
    expect(MunicipalitiesRepository.data).toHaveLength(1);
  });

  it('warns about duplicated provider ids but keeps inserting the stations', async () => {
    stubProviderFetch({
      stations: stationsResponse([stationEntry(), stationEntry()]),
      municipalities: municipalitiesResponse(),
    });

    await realtimeDataService.loadAll();

    expect(await FuelStationsTable.count()).toBe(2);
    expect(logger.warn).toHaveBeenCalledWith(expect.stringContaining('Duplicated IDs'));
  });
});
